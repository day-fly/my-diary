const { test } = require("node:test");
const assert = require("node:assert/strict");
const { readFileSync } = require("node:fs");
const { JSDOM } = require("jsdom");
const source = readFileSync("assets/js/background-music.js", "utf8");
const markup = readFileSync("_includes/background-music.html", "utf8").replace(/{{.*?}}/g, "/my-diary/assets/audio/touching-moments-one-pulse.mp3");
const key = "diary:music:/my-diary/assets/audio/touching-moments-one-pulse.mp3";
function setup({ saved, preference, blocked = false } = {}) {
  const dom = new JSDOM(markup, { url: "https://example.com/my-diary/", runScripts: "outside-only" });
  const w = dom.window, q = selector => w.document.querySelector(selector), audio = q("audio");
  let plays = 0, paused = true;
  const requests = [];
  Object.defineProperty(audio, "paused", { get: () => paused });
  Object.defineProperty(audio, "duration", { value: 102 });
  audio.play = () => {
    plays++;
    paused = false;
    return new Promise((resolve, reject) => requests.push({ resolve, reject }));
  };
  audio.pause = () => { if (!paused) { paused = true; audio.dispatchEvent(new w.Event("pause")); } };
  audio.load = () => {};
  if (saved) w.sessionStorage.setItem(key, JSON.stringify(saved));
  if (preference) w.localStorage.setItem(key + ":preference", JSON.stringify(preference));
  if (blocked) ["sessionStorage", "localStorage"].forEach(name => Object.defineProperty(w, name, { get() { throw new Error("blocked"); } }));
  w.eval(source);
  return { w, q, audio, requests, plays: () => plays, click: () => q(".music-toggle").click(), state: () => q(".music-player").dataset.state };
}
test("first visit attempts quiet autoplay with an explicit pause control", async () => {
  const a = setup();
  assert.equal(a.plays(), 1);
  assert.equal(a.audio.volume, 0.2);
  assert.equal(a.audio.loop, true);
  assert.equal(a.state(), "loading");
  a.requests[0].resolve();
  await Promise.resolve();
  assert.equal(a.state(), "playing");
  assert.equal(a.q(".music-toggle").getAttribute("aria-label"), "배경음악 일시정지");
  a.w.close();
});
test("an explicit off preference suppresses autoplay and downloading on later visits", () => {
  const a = setup({ preference: { enabled: false, volume: 0.35 } });
  assert.equal(a.plays(), 0);
  assert.equal(a.audio.hasAttribute("src"), false);
  assert.equal(a.audio.volume, 0.35);
  a.click();
  assert.equal(a.plays(), 1);
  assert.equal(JSON.parse(a.w.localStorage.getItem(key + ":preference")).enabled, true);
  a.click();
  assert.equal(JSON.parse(a.w.localStorage.getItem(key + ":preference")).enabled, false);
  a.w.close();
});
test("canceling a slow autoplay cannot be undone by its late result", async () => {
  const a = setup();
  a.click();
  a.requests[0].resolve();
  await Promise.resolve();
  a.audio.dispatchEvent(new a.w.Event("playing"));
  assert.equal(a.audio.paused, true);
  assert.equal(a.state(), "paused");
  assert.equal(JSON.parse(a.w.localStorage.getItem(key + ":preference")).enabled, false);
  a.w.close();
});
test("page navigation resumes position without turning an enabled preference off", async () => {
  const a = setup({ saved: { position: 38, volume: 0.25 } });
  a.audio.dispatchEvent(new a.w.Event("loadedmetadata"));
  assert.equal(a.audio.currentTime, 38);
  a.requests[0].resolve();
  await Promise.resolve();
  a.q("#music-volume").value = "0";
  a.q("#music-volume").dispatchEvent(new a.w.Event("input"));
  a.audio.currentTime = 51;
  a.w.dispatchEvent(new a.w.Event("pagehide"));
  const saved = JSON.parse(a.w.sessionStorage.getItem(key));
  const preference = JSON.parse(a.w.localStorage.getItem(key + ":preference"));
  assert.deepEqual(saved, { position: 51, volume: 0, enabled: true });
  assert.equal(a.audio.paused, true);
  a.w.close();
  const b = setup({ saved, preference });
  assert.equal(b.plays(), 1);
  assert.equal(b.audio.muted, true);
  b.audio.dispatchEvent(new b.w.Event("loadedmetadata"));
  assert.equal(b.audio.currentTime, 51);
  b.w.close();
});
test("blocked autoplay is quiet and a manual play recovers even with storage blocked", async () => {
  const a = setup({ blocked: true });
  a.requests[0].reject({ name: "NotAllowedError" });
  await Promise.resolve();
  assert.equal(a.state(), "paused");
  assert.equal(a.q(".music-message").hidden, true);
  assert.match(a.q(".music-help").textContent, /재생 버튼/);
  a.click();
  a.requests[1].resolve();
  await Promise.resolve();
  assert.equal(a.state(), "playing");
  a.q(".music-details").click();
  a.audio.dispatchEvent(new a.w.Event("error"));
  assert.equal(a.state(), "paused");
  assert.match(a.q(".music-message").textContent, /불러오지 못/);
  a.click();
  assert.equal(a.q(".music-message").hidden, true);
  a.w.close();
});
test("compact controls retain playback, volume, credits, and keyboard dismissal", async () => {
  const a = setup();
  Object.defineProperty(a.w, "scrollY", { value: 300 });
  a.w.dispatchEvent(new a.w.Event("scroll"));
  assert.equal(a.q(".music-player").classList.contains("is-compact"), true);
  a.requests[0].resolve();
  await Promise.resolve();
  const details = a.q(".music-details");
  details.click();
  assert.equal(a.q(".music-panel").hidden, false);
  a.q(".music-panel-toggle").click();
  assert.equal(a.audio.paused, true);
  assert.equal(JSON.parse(a.w.localStorage.getItem(key + ":preference")).enabled, false);
  assert.match(a.q(".music-credit a").href, /incompetech.com.*USUAN1100039/);
  assert.equal(a.q(".music-license").href, "https://creativecommons.org/licenses/by/4.0/");
  a.q("#music-volume").dispatchEvent(new a.w.KeyboardEvent("keydown", { key: "Escape", bubbles: true }));
  assert.equal(a.q(".music-panel").hidden, true);
  assert.equal(a.w.document.activeElement, details);
  a.w.close();
});
test("back-forward cache resumes only when the listener kept music enabled", () => {
  const a = setup();
  a.w.dispatchEvent(new a.w.Event("pagehide"));
  const event = new a.w.Event("pageshow");
  Object.defineProperty(event, "persisted", { value: true });
  a.w.dispatchEvent(event);
  assert.equal(a.plays(), 2);
  a.click();
  a.w.dispatchEvent(new a.w.Event("pagehide"));
  a.w.dispatchEvent(event);
  assert.equal(a.plays(), 2);
  a.w.close();
});
